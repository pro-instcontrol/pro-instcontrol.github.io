def _valve(cx, cy, s=6, color=INK):
    """Bow-tie hand-valve / actuator symbol centred on a pipe."""
    return (_poly([(cx - s, cy - s), (cx - s, cy + s), (cx, cy)],
                  fill="#ffffff", sw=1.0, color=color, close=True)
            + _poly([(cx + s, cy - s), (cx + s, cy + s), (cx, cy)],
                    fill="#ffffff", sw=1.0, color=color, close=True))


def _vcontact(x, y, nc=False, color=INK):
    """Contact drawn across a vertical rung (rails run horizontally)."""
    o = [_line(x - 8, y - 3, x + 8, y - 3, sw=1.4, color=color),
         _line(x - 8, y + 3, x + 8, y + 3, sw=1.4, color=color)]
    if nc:
        o.append(_line(x - 7, y + 7, x + 7, y - 7, sw=1.2, color=color))
    return "".join(o)


def _switch(x, y, color=INK):
    """Open switch / level-switch pickoff symbol on a vertical supply rail."""
    return (_circle(x, y, 3.5, fill="#ffffff", sw=1.1, color=color)
            + _line(x - 3.5, y, x - 18, y, color=color))


